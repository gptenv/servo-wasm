import { describe, expect, it } from 'vitest';
import { HeaderGenerator } from 'header-generator';
import { applyChromeRequestDefaults, CHROME_REQUEST_PROFILE } from '../src/chrome-request-profile';

describe('Chrome request defaults', () => {
  it('matches the current Chrome 157 Windows profile generated by header-generator', () => {
    const generated = new HeaderGenerator({
      browsers: [{ name: 'chrome', minVersion: 157, maxVersion: 157, httpVersion: '2' }],
      operatingSystems: ['windows'],
      devices: ['desktop'],
      locales: ['en-US', 'en'],
      httpVersion: '2',
      strict: true,
    }).getHeaders();

    expect(generated['user-agent']).toBe(CHROME_REQUEST_PROFILE.userAgent);
    expect(generated['sec-ch-ua']).toBe(CHROME_REQUEST_PROFILE.secChUa);
    expect(generated['sec-ch-ua-mobile']).toBe(CHROME_REQUEST_PROFILE.secChUaMobile);
    expect(generated['sec-ch-ua-platform']).toBe(CHROME_REQUEST_PROFILE.secChUaPlatform);
  });

  it('adds Chrome defaults by destination while preserving custom header overrides', () => {
    const request = new Request('https://example.com/image.png', {
      headers: {
        'User-Agent': 'CustomBrowser/1.0',
        Accept: 'application/x-custom',
        'Sec-Fetch-Dest': 'image',
        'Sec-Fetch-Mode': 'no-cors',
      },
    });
    const result = applyChromeRequestDefaults(request);

    expect(result.headers.get('user-agent')).toBe('CustomBrowser/1.0');
    expect(result.headers.get('accept')).toBe('application/x-custom');
    expect(result.headers.get('sec-ch-ua-platform')).toBe('"Windows"');
    expect(result.headers.get('accept-language')).toBe('en-US,en;q=0.9');
  });

  it('replaces Servo defaults with Chrome values for navigation and image requests', () => {
    const navigation = applyChromeRequestDefaults(new Request('https://example.com/', {
      headers: {
        'User-Agent': 'Mozilla/5.0 (X11; Linux x86_64; rv:153.0) Servo/0.6.0 Firefox/153.0',
        Accept: 'text/html,application/xhtml+xml,application/xml;q=0.9,*/*;q=0.8',
        'Sec-Fetch-Dest': 'document',
        'Sec-Fetch-Mode': 'navigate',
      },
    }));
    const image = applyChromeRequestDefaults(new Request('https://example.com/image.png', {
      headers: {
        Accept: 'image/png,image/svg+xml,image/*;q=0.8,*/*;q=0.5',
        'Sec-Fetch-Dest': 'image',
      },
    }));

    expect(navigation.headers.get('user-agent')).toBe(CHROME_REQUEST_PROFILE.userAgent);
    expect(navigation.headers.get('accept')).toBe(CHROME_REQUEST_PROFILE.acceptDocument);
    expect(navigation.headers.get('upgrade-insecure-requests')).toBe('1');
    expect(image.headers.get('accept')).toBe(CHROME_REQUEST_PROFILE.acceptImage);
  });

  it('uses the request destination forwarded by the Servo host adapter', () => {
    const navigation = applyChromeRequestDefaults(new Request('https://example.com/', {
      headers: { Accept: '*/*', 'Accept-Language': 'en-US' },
    }), { destination: 'Document' });

    expect(navigation.headers.get('accept')).toBe(CHROME_REQUEST_PROFILE.acceptDocument);
    expect(navigation.headers.get('accept-language')).toBe(CHROME_REQUEST_PROFILE.acceptLanguage);
    expect(navigation.headers.get('sec-fetch-dest')).toBe('document');
    expect(navigation.headers.get('sec-fetch-mode')).toBe('navigate');
  });
});
